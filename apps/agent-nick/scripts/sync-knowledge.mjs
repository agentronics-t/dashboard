// Compiles src/knowledge/**/*.md into src/knowledge/pack.generated.ts.
// `--pull <ref>` first re-downloads Google's WebMCP guides at that git ref.
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../src/knowledge/", import.meta.url).pathname;
const GUIDES = ["webmcp", "agentic-forms", "agentic-javascript-tools"];

const pull = process.argv.indexOf("--pull");
if (pull !== -1) {
  const ref = process.argv[pull + 1];
  if (!ref) throw new Error("--pull needs a git ref (commit sha or branch)");
  for (const g of GUIDES) {
    const url = `https://raw.githubusercontent.com/GoogleChrome/modern-web-guidance/${ref}/skills/modern-web-guidance/guides/webmcp/${g}.md`;
    const text = execFileSync("curl", ["-fsSL", url], { encoding: "utf8" });
    writeFileSync(join(root, "webmcp", `${g}.md`), text);
  }
}

const read = (dir) =>
  existsSync(join(root, dir))
    ? readdirSync(join(root, dir))
        .filter((f) => f.endsWith(".md") && f !== "README.md")
        .sort()
        .map((f) => ({ name: `${dir}/${f}`, text: readFileSync(join(root, dir, f), "utf8") }))
    : [];

const webmcp = GUIDES.map((g) => ({ name: `webmcp/${g}.md`, text: readFileSync(join(root, "webmcp", `${g}.md`), "utf8") }));
const sdk = read("sdk");

writeFileSync(
  join(root, "pack.generated.ts"),
  `// GENERATED by scripts/sync-knowledge.mjs — do not edit. Sources: src/knowledge/**/*.md\n` +
    `// webmcp/: GoogleChrome/modern-web-guidance (Apache-2.0, see webmcp/LICENSE).\n\n` +
    `export const WEBMCP_GUIDES: { name: string; text: string }[] = ${JSON.stringify(webmcp, null, 2)};\n\n` +
    `export const SDK_DOCS: { name: string; text: string }[] = ${JSON.stringify(sdk, null, 2)};\n`
);
console.log(`knowledge pack: ${webmcp.length} WebMCP guides, ${sdk.length} SDK docs`);
